/**
 * Generates physical SAT collision obstacles from a city's buildings, roundabouts, and parked vehicles.
 */
export function buildCityCollisionObstacles(
  cityId: string,
  buildings: CityBuildingSpec[],
  roundabouts: CityRoundaboutSpec[],
  parkedVehicles: CityParkedVehicleSpec[]
): ObstacleDefinition[] {
  const obstacles: ObstacleDefinition[] = [];

  for (let i = 0; i < buildings.length; i++) {
    const b = buildings[i];
    obstacles.push({
      id: `${cityId}-bldg-${b.id}`,
      kind: 'building',
      label: b.name,
      position: b.position,
      rotationY: b.rotationY ?? 0,
      dimensions: {
        width: b.dimensions[0],
        height: b.dimensions[1],
        length: b.dimensions[2],
      },
      color: b.primaryColor,
    });
  }

  for (let i = 0; i < roundabouts.length; i++) {
    const r = roundabouts[i];
    const d = r.islandRadius * 1.85;
    obstacles.push({
      id: `${cityId}-island-${r.id}`,
      kind: 'island',
      label: `${r.name} Island`,
      position: [r.center[0], 0, r.center[1]],
      rotationY: 0,
      dimensions: {
        width: d,
        height: 0.45,
        length: d,
      },
    });
  }

  for (let i = 0; i < parkedVehicles.length; i++) {
    const v = parkedVehicles[i];
    obstacles.push({
      id: `${cityId}-veh-${v.id}`,
      kind: 'parked-car',
      label: v.label,
      position: v.position,
      rotationY: v.rotationY,
      dimensions: v.dimensions,
      color: v.color,
    });
  }

  return obstacles;
}

